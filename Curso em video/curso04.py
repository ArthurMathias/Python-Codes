print("Descubra o Dobro, Triplo e raiz quadrada")
numero = int(input("Digite um número: "))
dobro = numero * 2
triplo = numero * 3
raiz = numero * (1/2)

print(f"O dobro de {numero} é {dobro}")
print(f"O Triplo de {numero} é {triplo}")
print(f"A Raiz quadrada de {numero} é {raiz:.2f}")

